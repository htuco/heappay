import io
from datetime import date
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

_LOGO_PATH = Path(__file__).resolve().parent.parent.parent / "assets" / "branding" / "logo.png"
_LOGO_ASPECT = 366 / 1431  # native logo.png height / width

PRIMARY = colors.HexColor("#1E9DF1")
PRIMARY_DARK = colors.HexColor("#254BB2")
FOREGROUND = colors.HexColor("#0F1419")
MUTED = colors.HexColor("#4778A9")
BORDER = colors.HexColor("#E1EAEF")
WHITE = colors.white

_TOP_MARGIN = 32 * mm
_SIDE_MARGIN = 20 * mm
_BOTTOM_MARGIN = 20 * mm

_styles = getSampleStyleSheet()
TITLE_STYLE = ParagraphStyle(
    "ExportTitle", parent=_styles["Heading1"], textColor=PRIMARY_DARK, fontSize=20, spaceAfter=2,
)
SUBTITLE_STYLE = ParagraphStyle(
    "ExportSubtitle", parent=_styles["Normal"], textColor=MUTED, fontSize=10, spaceAfter=10,
)
SECTION_STYLE = ParagraphStyle(
    "ExportSection", parent=_styles["Heading2"], textColor=FOREGROUND, fontSize=13, spaceBefore=14, spaceAfter=6,
)
NOTE_STYLE = ParagraphStyle(
    "ExportNote", parent=_styles["Normal"], textColor=MUTED, fontSize=9, spaceBefore=6,
)


def _draw_header_footer(canvas, doc) -> None:
    canvas.saveState()
    width, height = doc.pagesize

    canvas.setFillColor(PRIMARY)
    canvas.rect(0, height - 4, width, 4, fill=1, stroke=0)

    if _LOGO_PATH.exists():
        logo_w = 28 * mm
        logo_h = logo_w * _LOGO_ASPECT
        canvas.drawImage(
            str(_LOGO_PATH),
            doc.leftMargin,
            height - 4 - 8 * mm - logo_h,
            width=logo_w,
            height=logo_h,
            mask="auto",
        )

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(doc.leftMargin, 12 * mm, f"Generated by heap on {date.today().isoformat()}")
    canvas.drawRightString(width - doc.rightMargin, 12 * mm, f"Page {canvas.getPageNumber()}")
    canvas.restoreState()


def _new_doc() -> tuple[SimpleDocTemplate, io.BytesIO]:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        topMargin=_TOP_MARGIN,
        bottomMargin=_BOTTOM_MARGIN,
        leftMargin=_SIDE_MARGIN,
        rightMargin=_SIDE_MARGIN,
        title="heap export",
    )
    return doc, buffer


def _build(doc: SimpleDocTemplate, buffer: io.BytesIO, flowables: list) -> bytes:
    doc.build(flowables, onFirstPage=_draw_header_footer, onLaterPages=_draw_header_footer)
    return buffer.getvalue()


def _table(header: list[str], rows: list[list[str]], col_widths: list[float] | None = None) -> Table:
    data = [header] + rows
    table = Table(data, colWidths=col_widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
        ("TOPPADDING", (0, 0), (-1, 0), 6),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, colors.HexColor("#F5F9FC")]),
        ("TEXTCOLOR", (0, 1), (-1, -1), FOREGROUND),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]
    table.setStyle(TableStyle(style))
    return table


def _user_name(user) -> str:
    return f"{user.first_name} {user.last_name}"


def build_wallet_summary_pdf(user, cards: list) -> bytes:
    doc, buffer = _new_doc()
    flowables = [
        Paragraph("Wallet Summary", TITLE_STYLE),
        Paragraph(f"{_user_name(user)} &bull; {user.email}", SUBTITLE_STYLE),
    ]

    total_balance = sum(card.balance for card in cards) if cards else 0
    flowables.append(Paragraph(f"Total balance: ${total_balance:,.2f}", SECTION_STYLE))
    flowables.append(Spacer(1, 4))

    if cards:
        rows = []
        for card in cards:
            card_type = (
                f"{card.card_type.vendor} {card.card_type.type_name}" if card.card_type else "Card"
            )
            status = card.status.status_name if card.status else "unknown"
            rows.append([
                card_type,
                f"*{card.last_four}",
                status,
                card.expires_at.isoformat() if card.expires_at else "-",
                f"${card.balance:,.2f}",
            ])
        table = _table(
            ["Card", "Number", "Status", "Expires", "Balance"],
            rows,
            col_widths=[55 * mm, 25 * mm, 25 * mm, 25 * mm, 30 * mm],
        )
        flowables.append(table)
    else:
        flowables.append(Paragraph("No cards found.", NOTE_STYLE))

    return _build(doc, buffer, flowables)


def _counterparty(txn, user_id: int) -> tuple[str, str]:
    """Returns (direction, counterparty_name). direction is '+' (incoming) or '-' (outgoing)."""
    if txn.sender_card and txn.sender_card.user_id == user_id:
        recipient_user = txn.recipient_card.user if txn.recipient_card else None
        name = f"{recipient_user.first_name} {recipient_user.last_name}" if recipient_user else "-"
        return "-", name
    sender_user = txn.sender_card.user if txn.sender_card else None
    name = f"{sender_user.first_name} {sender_user.last_name}" if sender_user else "External"
    return "+", name


def build_transactions_pdf(
    user, transactions: list, total_count: int, shown_count: int
) -> bytes:
    doc, buffer = _new_doc()
    flowables = [
        Paragraph("Transaction List", TITLE_STYLE),
        Paragraph(f"{_user_name(user)} &bull; {user.email}", SUBTITLE_STYLE),
    ]

    if shown_count < total_count:
        flowables.append(
            Paragraph(f"Showing the most recent {shown_count} of {total_count} transactions.", NOTE_STYLE)
        )
        flowables.append(Spacer(1, 6))

    if transactions:
        rows = []
        for txn in transactions:
            direction, counterparty = _counterparty(txn, user.user_id)
            txn_type = txn.transaction_type.name if txn.transaction_type else "transfer"
            category = txn.category.name if txn.category else "Uncategorised"
            status = txn.status.name if txn.status else "unknown"
            rows.append([
                txn.created_at.strftime("%Y-%m-%d"),
                txn_type,
                category,
                counterparty,
                f"{direction}${txn.amount:,.2f}",
                status,
            ])
        table = _table(
            ["Date", "Type", "Category", "Counterparty", "Amount", "Status"],
            rows,
            col_widths=[22 * mm, 25 * mm, 28 * mm, 40 * mm, 25 * mm, 25 * mm],
        )
        flowables.append(table)
    else:
        flowables.append(Paragraph("No transactions found.", NOTE_STYLE))

    return _build(doc, buffer, flowables)


def build_monthly_report_pdf(
    user, summary_points: list[dict], category_breakdown: list[dict], months: int
) -> bytes:
    doc, buffer = _new_doc()
    period_label = "month" if months == 1 else "months"
    flowables = [
        Paragraph("Monthly Report", TITLE_STYLE),
        Paragraph(
            f"{_user_name(user)} &bull; {user.email} &bull; last {months} {period_label}", SUBTITLE_STYLE
        ),
        Paragraph("Income &amp; Expense", SECTION_STYLE),
    ]

    if summary_points:
        rows = []
        for point in summary_points:
            income = point["income"]
            expense = point["expense"]
            net = income - expense
            rows.append([
                point["period"],
                f"${income:,.2f}",
                f"${expense:,.2f}",
                f"${net:,.2f}",
            ])
        flowables.append(
            _table(
                ["Month", "Income", "Expense", "Net"],
                rows,
                col_widths=[35 * mm, 35 * mm, 35 * mm, 35 * mm],
            )
        )
    else:
        flowables.append(Paragraph("No transaction activity in this period.", NOTE_STYLE))

    flowables.append(Paragraph("Spending by Category", SECTION_STYLE))
    if category_breakdown:
        rows = [
            [
                item["name"] if item["name"] is not None else "Uncategorised",
                f"${item['total']:,.2f}",
                str(item["count"]),
            ]
            for item in category_breakdown
        ]
        flowables.append(
            _table(
                ["Category", "Total spent", "Transactions"],
                rows,
                col_widths=[70 * mm, 40 * mm, 30 * mm],
            )
        )
    else:
        flowables.append(Paragraph("No categorised spending in this period.", NOTE_STYLE))

    return _build(doc, buffer, flowables)
