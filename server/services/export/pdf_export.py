def _draw_header_footer(canvas, doc) -> None:
    canvas.saveState()
    width, height = doc.pagesize

    canvas.setFillColor(PRIMARY)
    canvas.rect(0, height - 4, width, 4, fill=1, stroke=0)

    if _LOGO_PATH.exists():
        logo_w = 28 * mm
        logo_h = logo_w * _LOGO_ASPECT
        canvas.drawImage(
            str(_LOGO_PATH),
            doc.leftMargin,
            height - 4 - 8 * mm - logo_h,
            width=logo_w,
            height=logo_h,
            mask="auto",
        )

    canvas.setFont(BASE_FONT, 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(doc.leftMargin, 12 * mm, f"Generated by heap on {date.today().isoformat()}")
    # The "Page X of Y" string is drawn by _NumberedCanvas once the total is known.
    canvas.restoreState()


class _NumberedCanvas(_canvas.Canvas):
    """Two-pass canvas so the footer can render 'Page X of Y' with the real total."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        total = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_page_number(total)
            super().showPage()
        super().save()

    def _draw_page_number(self, total: int) -> None:
        self.saveState()
        self.setFont(BASE_FONT, 8)
        self.setFillColor(MUTED)
        self.drawRightString(
            self._pagesize[0] - _SIDE_MARGIN,
            12 * mm,
            f"Page {self._pageNumber} of {total}",
        )
        self.restoreState()


def _new_doc() -> tuple[SimpleDocTemplate, io.BytesIO]:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        topMargin=_TOP_MARGIN,
        bottomMargin=_BOTTOM_MARGIN,
        leftMargin=_SIDE_MARGIN,
        rightMargin=_SIDE_MARGIN,
        title="heap export",
    )
    return doc, buffer


def _build(doc: SimpleDocTemplate, buffer: io.BytesIO, flowables: list) -> bytes:
    doc.build(
        flowables,
        onFirstPage=_draw_header_footer,
        onLaterPages=_draw_header_footer,
        canvasmaker=_NumberedCanvas,
    )
    return buffer.getvalue()


def _table(
    header: list,
    rows: list[list],
    col_widths: list[float] | None = None,
    extra_styles: list | None = None,
) -> Table:
    data = [header] + rows
    table = Table(data, colWidths=col_widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), BASE_FONT_BOLD),
        ("FONTNAME", (0, 1), (-1, -1), BASE_FONT),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("LINEBELOW", (0, 0), (-1, -1), 0.5, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, SURFACE]),
        ("TEXTCOLOR", (0, 1), (-1, -1), FOREGROUND),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]
    if extra_styles:
        style.extend(extra_styles)
    table.setStyle(TableStyle(style))
    return table


def _user_name(user) -> str:
    return f"{user.first_name} {user.last_name}"


def _money(amount) -> str:
    sign = "-" if amount < 0 else ""
    return f"{sign}${abs(amount):,.2f}"


def humanize(name) -> str:
    """Turn a raw snake_case code into a readable label (food_dining -> Food Dining)."""
    if name is None:
        return ""
    return str(name).replace("_", " ").title()


def _completed(status_name) -> bool:
    return (status_name or "").strip().lower() == "completed"


def compute_transaction_totals(transactions: list, user_id: int) -> tuple[float, float, float]:
    """Sum money that actually moved: completed transactions only. Returns
    (total_in, total_out, net). Cancelled/failed/pending rows are excluded so
    the summary band never counts money that never settled."""
    total_in = 0
    total_out = 0
    for txn in transactions:
        status = txn.status.name if txn.status else ""
        if not _completed(status):
            continue
        direction, _ = _counterparty(txn, user_id)
        if direction == "+":
            total_in += txn.amount
        else:
            total_out += txn.amount
    return total_in, total_out, total_in - total_out


def _hex(color) -> str:
    return f"#{color.hexval()[2:]}"


def _truncate(text, limit: int = 32) -> str:
    text = str(text if text is not None else "")
    if len(text) <= limit:
        return text
    return text[: limit - 1].rstrip() + "\u2026"


def _status_palette(status_name: str) -> tuple:
    key = (status_name or "").strip().lower()
    return _STATUS_PALETTE.get(key, _STATUS_DEFAULT)


def _summary_band(count: int, total_in, total_out, net) -> Table:
    label_style = ParagraphStyle(
        "SumLabel", parent=NOTE_STYLE, textColor=MUTED, fontSize=7.5, leading=9,
        spaceBefore=0, spaceAfter=0, fontName="Helvetica-Bold",
    )

    def value_para(text: str, color) -> Paragraph:
        return Paragraph(
            f'<font color="{_hex(color)}">{text}</font>',
            ParagraphStyle(
                "SumValue", parent=_styles["Normal"], fontSize=13, leading=15,
                fontName="Helvetica-Bold",
            ),
        )

    net_color = INCOMING if net >= 0 else OUTGOING
    header_cells = [
        Paragraph("TRANSACTIONS", label_style),
        Paragraph("TOTAL IN", label_style),
        Paragraph("TOTAL OUT", label_style),
        Paragraph("NET", label_style),
    ]
    value_cells = [
        value_para(str(count), FOREGROUND),
        value_para(_money(total_in), INCOMING),
        value_para(_money(total_out), OUTGOING),
        value_para(_money(net), net_color),
    ]
    col = _USABLE_WIDTH / 4
    band = Table([header_cells, value_cells], colWidths=[col, col, col, col])
    band.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), SURFACE),
            ("BOX", (0, 0), (-1, -1), 0.75, BORDER),
            ("LINEAFTER", (0, 0), (-2, -1), 0.5, BORDER),
            ("TOPPADDING", (0, 0), (-1, 0), 9),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 1),
            ("TOPPADDING", (0, 1), (-1, 1), 0),
            ("BOTTOMPADDING", (0, 1), (-1, 1), 9),
            ("LEFTPADDING", (0, 0), (-1, -1), 12),
            ("RIGHTPADDING", (0, 0), (-1, -1), 12),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    return band


def build_wallet_summary_pdf(user, cards: list) -> bytes:
    doc, buffer = _new_doc()
    flowables = [
        Paragraph("Wallet Summary", TITLE_STYLE),
        Paragraph(f"{_user_name(user)} &bull; {user.email}", SUBTITLE_STYLE),
    ]

    total_balance = sum(card.balance for card in cards) if cards else 0
    flowables.append(Paragraph(f"Total balance: ${total_balance:,.2f}", SECTION_STYLE))
    flowables.append(Spacer(1, 4))

    if cards:
        rows = []
        for card in cards:
            card_type = (
                f"{card.card_type.vendor} {card.card_type.type_name}" if card.card_type else "Card"
            )
            status = card.status.status_name if card.status else "unknown"
            rows.append([
                card_type,
                f"*{card.last_four}",
                status,
                card.expires_at.isoformat() if card.expires_at else "-",
                f"${card.balance:,.2f}",
            ])
        table = _table(
            ["Card", "Number", "Status", "Expires", "Balance"],
            rows,
            col_widths=[55 * mm, 25 * mm, 25 * mm, 25 * mm, 30 * mm],
        )
        flowables.append(table)
    else:
        flowables.append(Paragraph("No cards found.", NOTE_STYLE))

    return _build(doc, buffer, flowables)


def _counterparty(txn, user_id: int) -> tuple[str, str]:
    """Returns (direction, counterparty_name). direction is '+' (incoming) or '-' (outgoing)."""
    if txn.sender_card and txn.sender_card.user_id == user_id:
        recipient_user = txn.recipient_card.user if txn.recipient_card else None
        name = f"{recipient_user.first_name} {recipient_user.last_name}" if recipient_user else "-"
        return "-", name
    sender_user = txn.sender_card.user if txn.sender_card else None
    name = f"{sender_user.first_name} {sender_user.last_name}" if sender_user else "External"
    return "+", name


def build_transactions_pdf(
    user,
    transactions: list,
    total_count: int,
    shown_count: int,
    context_line: str | None = None,
) -> bytes:
    doc, buffer = _new_doc()
    flowables = [
        Paragraph("Transaction Statement", TITLE_STYLE),
        Paragraph(
            f"{_user_name(user)} &bull; {user.email} &bull; Generated {date.today().strftime('%b %d, %Y')}",
            SUBTITLE_STYLE,
        ),
    ]

    table_rows = []
    status_styles: list = []
    for index, txn in enumerate(transactions):
        direction, counterparty = _counterparty(txn, user.user_id)
        amount = txn.amount
        amount_color = INCOMING if direction == "+" else OUTGOING

        txn_type = txn.transaction_type.name if txn.transaction_type else "transfer"
        category = txn.category.name if txn.category else "Uncategorised"
        status = txn.status.name if txn.status else "unknown"
        bg, fg = _status_palette(status)

        amount_para = Paragraph(
            f'<font color="{_hex(amount_color)}">{direction}{_money(amount)}</font>',
            AMOUNT_STYLE,
        )
        status_para = Paragraph(
            f'<font color="{_hex(fg)}">{humanize(status)}</font>', PILL_STYLE
        )
        table_rows.append([
            Paragraph(txn.created_at.strftime("%b %d, %Y"), CELL_STYLE),
            Paragraph(_truncate(humanize(txn_type), 18), CELL_STYLE),
            Paragraph(_truncate(humanize(category), 20), CELL_STYLE),
            Paragraph(_truncate(counterparty, 30), CELL_STYLE),
            amount_para,
            status_para,
        ])
        row = index + 1  # +1 for header row
        status_styles.append(("BACKGROUND", (5, row), (5, row), bg))

    total_in, total_out, net = compute_transaction_totals(transactions, user.user_id)
    flowables.append(_summary_band(shown_count, total_in, total_out, net))
    flowables.append(Spacer(1, 6))

    caption = "Totals cover completed transactions only."
    if shown_count < total_count:
        caption += (
            f" This export is capped at the most recent {shown_count} of "
            f"{total_count} matching transactions."
        )
    flowables.append(Paragraph(caption, NOTE_STYLE))

    if context_line:
        flowables.append(Paragraph(context_line, CONTEXT_STYLE))
    flowables.append(Spacer(1, 6))

    if table_rows:
        extra_styles = [
            ("ALIGN", (4, 0), (4, -1), "RIGHT"),
            ("TOPPADDING", (0, 1), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 1), (-1, -1), 5),
            *status_styles,
        ]
        table = _table(
            ["Date", "Type", "Category", "Counterparty", "Amount", "Status"],
            table_rows,
            col_widths=[24 * mm, 24 * mm, 30 * mm, 45 * mm, 26 * mm, 26 * mm],
            extra_styles=extra_styles,
        )
        flowables.append(table)
    else:
        flowables.append(Paragraph("No transactions found.", NOTE_STYLE))

    return _build(doc, buffer, flowables)


def build_monthly_report_pdf(
    user, summary_points: list[dict], category_breakdown: list[dict], months: int
) -> bytes:
    doc, buffer = _new_doc()
    period_label = "month" if months == 1 else "months"
    flowables = [
        Paragraph("Monthly Report", TITLE_STYLE),
        Paragraph(
            f"{_user_name(user)} &bull; {user.email} &bull; last {months} {period_label}", SUBTITLE_STYLE
        ),
        Paragraph("Income &amp; Expense", SECTION_STYLE),
    ]

    if summary_points:
        rows = []
        for point in summary_points:
            income = point["income"]
            expense = point["expense"]
            net = income - expense
            rows.append([
                point["period"],
                _money(income),
                _money(expense),
                _money(net),
            ])
        flowables.append(
            _table(
                ["Month", "Income", "Expense", "Net"],
                rows,
                col_widths=[35 * mm, 35 * mm, 35 * mm, 35 * mm],
            )
        )
    else:
        flowables.append(Paragraph("No transaction activity in this period.", NOTE_STYLE))

    flowables.append(Paragraph("Spending by Category", SECTION_STYLE))
    if category_breakdown:
        rows = [
            [
                humanize(item["name"]) if item["name"] is not None else "Uncategorised",
                _money(item["total"]),
                str(item["count"]),
            ]
            for item in category_breakdown
        ]
        flowables.append(
            _table(
                ["Category", "Total spent", "Transactions"],
                rows,
                col_widths=[70 * mm, 40 * mm, 30 * mm],
            )
        )
    else:
        flowables.append(Paragraph("No categorised spending in this period.", NOTE_STYLE))

    return _build(doc, buffer, flowables)
